create table if not exists public.tipos_conexion (
  id smallint generated by default as identity primary key,
  codigo varchar(40) not null unique,
  nombre varchar(100) not null,
  descripcion text,
  activo boolean not null default true
);

create table if not exists public.conexiones (
  id uuid primary key default gen_random_uuid(),
  id_edificio uuid not null references public.edificios(id) on delete restrict,
  id_tipo_conexion smallint not null references public.tipos_conexion(id) on delete restrict,
  codigo varchar(80) not null,
  nombre varchar(150) not null,
  configuracion jsonb not null default '{}'::jsonb,
  activo boolean not null default true,
  fecha_alta date not null default current_date,
  fecha_baja date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint conexiones_codigo_edificio_uq unique (id_edificio, codigo),
  constraint conexiones_configuracion_objeto_ck
    check (jsonb_typeof(configuracion) = 'object'),
  constraint conexiones_fechas_ck check (fecha_baja is null or fecha_baja >= fecha_alta),
  constraint conexiones_estado_fecha_ck
    check ((activo and fecha_baja is null) or (not activo and fecha_baja is not null))
);

