create or replace function public.validar_dispositivo_conexion()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_edificio_recinto uuid;
  v_edificio_conexion uuid;
begin
  select p.id_edificio into v_edificio_recinto
  from public.recintos r
  join public.plantas p on p.id = r.id_planta
  where r.id = new.id_recinto;

  select c.id_edificio into v_edificio_conexion
  from public.conexiones c
  where c.id = new.id_conexion;

  if v_edificio_recinto is null or v_edificio_conexion is null then
    raise exception 'El recinto o la conexión indicada no existe';
  end if;

  if v_edificio_recinto <> v_edificio_conexion then
    raise exception 'El dispositivo y la conexión deben pertenecer al mismo edificio';
  end if;

  return new;
end;
$$;

create or replace function public.validar_sensor_conexion()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_edificio_sensor uuid;
  v_edificio_conexion uuid;
  v_recinto_dispositivo uuid;
  v_conexion_dispositivo uuid;
begin
  select p.id_edificio into v_edificio_sensor
  from public.recintos r
  join public.plantas p on p.id = r.id_planta
  where r.id = new.id_recinto;

  if v_edificio_sensor is null then
    raise exception 'El recinto del sensor no existe';
  end if;

  if new.id_dispositivo is not null then
    select d.id_recinto, d.id_conexion
      into v_recinto_dispositivo, v_conexion_dispositivo
    from public.dispositivos d
    where d.id = new.id_dispositivo;

    if not found then
      raise exception 'El dispositivo del sensor no existe';
    end if;

    if v_recinto_dispositivo <> new.id_recinto then
      raise exception 'El sensor asociado a un dispositivo debe compartir su recinto físico';
    end if;

    if v_conexion_dispositivo is null then
      raise exception 'El dispositivo debe tener una conexión';
    end if;
  else
    select c.id_edificio into v_edificio_conexion
    from public.conexiones c
    where c.id = new.id_conexion;

    if v_edificio_conexion is null then
      raise exception 'La conexión directa del sensor no existe';
    end if;

    if v_edificio_sensor <> v_edificio_conexion then
      raise exception 'El sensor y su conexión deben pertenecer al mismo edificio';
    end if;
  end if;

  return new;
end;
$$;

