begin;

-- =========================================================
-- USOS FINALES DE LA ENERGÍA Y DIAGRAMA SANKEY (21/10/2026)
--
--   FUENTES              VECTOR                 USOS            DETALLE
--   Red eléctrica ─┐
--   Fotovoltaica ──┼──► Electricidad ──────┬──► HVAC ──────┬──► Climatización
--   Eólica ────────┤                       │               └──► Renovación de aire
--                  └──► Exportada          ├──► Iluminación
--   Gas ───────────────────────────────────┼──► HVAC
--   Solar térmica ─┐                       │
--   Geotermia ─────┼──► Calor renovable ───┼──► HVAC
--   Biomasa ───────┘                       └──► Otros usos
--
-- · Electricidad consumida = importada + FV y eólica autoconsumidas
--   (la exportación se descuenta de cada renovable eléctrica en
--   proporción a su generación).
-- · Energía consumida por el edificio = electricidad consumida + gas
--   + calor renovable (decisión 21/10/2026).
-- · Lo que miden los submedidores asignados a un uso es MEDIDO.
-- · El resto (total − medido) se reparte con los porcentajes que
--   configure el Partner por edificio y tipo de energía (p. ej.
--   gas → 100 % climatización) y, si no hay porcentajes, va a
--   "Otros usos". Ese reparto se marca como ESTIMADO.
-- =========================================================

-- ---------------------------------------------------------
-- 1. Catálogo de usos (jerárquico; se asignan solo usos finales)
-- ---------------------------------------------------------
create table if not exists public.usos_energia (
  id smallint generated by default as identity primary key,
  codigo varchar(40) not null unique,
  nombre varchar(120) not null,
  id_padre smallint references public.usos_energia(id) on delete restrict,
  orden integer not null default 1,
  activo boolean not null default true
);

alter table public.usos_energia enable row level security;

drop policy if exists usos_energia_select on public.usos_energia;
create policy usos_energia_select on public.usos_energia
for select to authenticated using (true);

insert into public.usos_energia (codigo, nombre, orden) values
  ('HVAC', 'Climatización y ventilación (HVAC)', 1),
  ('ILUMINACION', 'Iluminación', 2),
  ('OTROS', 'Otros usos', 9)
on conflict (codigo) do nothing;

insert into public.usos_energia (codigo, nombre, id_padre, orden)
select x.codigo, x.nombre, p.id, x.orden
from (values ('HVAC_CLIMATIZACION', 'Climatización', 1),
             ('HVAC_RENOVACION', 'Renovación de aire', 2)) x(codigo, nombre, orden)
join public.usos_energia p on p.codigo = 'HVAC'
on conflict (codigo) do nothing;

create or replace function public.es_uso_final(p_id_uso smallint)
returns boolean
language sql
stable
set search_path = ''
as $$
  select exists (select 1 from public.usos_energia where id = p_id_uso)
     and not exists (select 1 from public.usos_energia where id_padre = p_id_uso);
$$;

-- ---------------------------------------------------------
-- 2. Uso que mide cada submedidor
-- ---------------------------------------------------------
alter table public.sensores
  add column if not exists id_uso_energia smallint references public.usos_energia(id) on delete restrict;

comment on column public.sensores.id_uso_energia is
  'Uso final que mide este submedidor (climatización, iluminación...). Vacío en contadores generales.';

create or replace function public.validar_uso_sensor()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.id_uso_energia is not null and not public.es_uso_final(new.id_uso_energia) then
    raise exception 'Asigne un uso final (por ejemplo "Climatización"), no un grupo ("HVAC")';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_sensores_validar_uso on public.sensores;
create trigger trg_sensores_validar_uso
before insert or update of id_uso_energia on public.sensores
for each row execute function public.validar_uso_sensor();

-- ---------------------------------------------------------
-- 3. Reparto estimado de la parte no medida
-- ---------------------------------------------------------
create table if not exists public.repartos_uso_edificio (
  id uuid primary key default gen_random_uuid(),
  id_edificio uuid not null references public.edificios(id) on delete restrict,
  tipo_energia varchar(20) not null,
  id_uso_energia smallint not null references public.usos_energia(id) on delete restrict,
  porcentaje numeric(5,2) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint repartos_uso_uq unique (id_edificio, tipo_energia, id_uso_energia),
  constraint repartos_uso_tipo_ck check (tipo_energia in ('ELECTRICIDAD', 'GAS', 'CALOR_RENOVABLE')),
  constraint repartos_uso_pct_ck check (porcentaje > 0 and porcentaje <= 100)
);

comment on table public.repartos_uso_edificio is
  'Cómo se reparte, por tipo de energía, la parte del consumo que no miden los submedidores. Lo que no sume 100 % va a "Otros usos".';

create or replace function public.validar_reparto_uso()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not public.es_uso_final(new.id_uso_energia) then
    raise exception 'El reparto debe hacerse sobre usos finales';
  end if;

  if (select coalesce(sum(porcentaje), 0) from public.repartos_uso_edificio
      where id_edificio = new.id_edificio and tipo_energia = new.tipo_energia and id <> new.id)
     + new.porcentaje > 100 then
    raise exception 'Los porcentajes de reparto de % superan el 100 %%', new.tipo_energia;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_repartos_uso_validar on public.repartos_uso_edificio;
create trigger trg_repartos_uso_validar
before insert or update on public.repartos_uso_edificio
for each row execute function public.validar_reparto_uso();

drop trigger if exists trg_repartos_uso_updated_at on public.repartos_uso_edificio;
create trigger trg_repartos_uso_updated_at
before update on public.repartos_uso_edificio
for each row execute function public.set_updated_at();

drop trigger if exists trg_auditoria on public.repartos_uso_edificio;
create trigger trg_auditoria after insert or update or delete on public.repartos_uso_edificio
for each row execute function public.auditar_cambio();

alter table public.repartos_uso_edificio enable row level security;

drop policy if exists repartos_uso_select on public.repartos_uso_edificio;
create policy repartos_uso_select on public.repartos_uso_edificio
for select to authenticated
using (private.usuario_tiene_acceso_edificio(id_edificio));

drop policy if exists repartos_uso_insert on public.repartos_uso_edificio;
create policy repartos_uso_insert on public.repartos_uso_edificio
for insert to authenticated
