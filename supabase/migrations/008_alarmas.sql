begin;

create table if not exists public.niveles_alarma (
  id smallint generated by default as identity primary key,
  codigo varchar(30) not null unique,
  nombre varchar(100) not null,
  prioridad smallint not null unique,
  envia_email boolean not null default false,
  activo boolean not null default true,
  constraint niveles_alarma_prioridad_ck check (prioridad >= 1)
);

insert into public.niveles_alarma (codigo, nombre, prioridad, envia_email) values
  ('INFORMATIVA', 'Informativa', 1, false),
  ('AVISO', 'Aviso', 2, false),
  ('IMPORTANTE', 'Importante', 3, true),
  ('CRITICA', 'Crítica', 4, true)
on conflict (codigo) do nothing;

create table if not exists public.reglas_alarma (
  id uuid primary key default gen_random_uuid(),
  id_edificio uuid not null references public.edificios(id) on delete restrict,
  id_sensor uuid references public.sensores(id) on delete restrict,
  id_magnitud_edificio uuid references public.magnitudes_edificio(id) on delete restrict,
  codigo varchar(80) not null,
  nombre varchar(180) not null,
  descripcion text,
  condicion varchar(30) not null,
  umbral numeric(24,8),
  umbral_inferior numeric(24,8),
  umbral_superior numeric(24,8),
  duracion_minutos integer not null default 0,
  id_nivel_alarma smallint not null references public.niveles_alarma(id) on delete restrict,
  ambito varchar(30) not null default 'EDIFICIO_COMPLETO',
  tipo_rearme varchar(20) not null default 'AUTOMATICO',
  activa boolean not null default true,
  fecha_alta date not null default current_date,
  fecha_baja date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reglas_alarma_codigo_edificio_uq unique (id_edificio, codigo),
  constraint reglas_alarma_fuente_ck
    check (num_nonnulls(id_sensor, id_magnitud_edificio) = 1),
  constraint reglas_alarma_condicion_ck
    check (condicion in (
      'MAYOR_QUE', 'MAYOR_IGUAL', 'MENOR_QUE', 'MENOR_IGUAL',
      'IGUAL', 'DISTINTO', 'ENTRE', 'FUERA_RANGO'
    )),
  constraint reglas_alarma_umbral_ck
    check (
      (
        condicion in ('MAYOR_QUE', 'MAYOR_IGUAL', 'MENOR_QUE', 'MENOR_IGUAL', 'IGUAL', 'DISTINTO')
        and umbral is not null
        and umbral_inferior is null
        and umbral_superior is null
      )
      or
      (
        condicion in ('ENTRE', 'FUERA_RANGO')
        and umbral is null
        and umbral_inferior is not null
        and umbral_superior is not null
        and umbral_inferior <= umbral_superior
      )
    ),
  constraint reglas_alarma_duracion_ck check (duracion_minutos >= 0),
  constraint reglas_alarma_ambito_ck
    check (ambito in ('EDIFICIO_COMPLETO', 'RECINTOS_SELECCIONADOS')),
  constraint reglas_alarma_rearme_ck check (tipo_rearme in ('AUTOMATICO', 'MANUAL')),
  constraint reglas_alarma_fechas_ck check (fecha_baja is null or fecha_baja >= fecha_alta),
  constraint reglas_alarma_estado_fecha_ck
    check ((activa and fecha_baja is null) or (not activa and fecha_baja is not null))
);

create index if not exists ix_reglas_alarma_edificio
  on public.reglas_alarma(id_edificio, activa);

create index if not exists ix_reglas_alarma_sensor
  on public.reglas_alarma(id_sensor) where id_sensor is not null;

create index if not exists ix_reglas_alarma_magnitud
  on public.reglas_alarma(id_magnitud_edificio)
  where id_magnitud_edificio is not null;

create table if not exists public.reglas_alarma_recintos (
  id_regla_alarma uuid not null references public.reglas_alarma(id) on delete restrict,
  id_recinto uuid not null references public.recintos(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (id_regla_alarma, id_recinto)
);

create table if not exists public.reglas_alarma_usuarios (
  id_regla_alarma uuid not null references public.reglas_alarma(id) on delete restrict,
  id_usuario uuid not null,
  creado_at timestamptz not null default now(),
  primary key (id_regla_alarma, id_usuario)
);

create table if not exists public.eventos_alarma (
  id uuid primary key default gen_random_uuid(),
  id_regla_alarma uuid not null references public.reglas_alarma(id) on delete restrict,
  id_sensor uuid references public.sensores(id) on delete restrict,
  id_magnitud_edificio uuid references public.magnitudes_edificio(id) on delete restrict,
  id_recinto uuid references public.recintos(id) on delete restrict,
  fecha_inicio timestamptz not null default now(),
  ultima_deteccion timestamptz not null default now(),
  fecha_fin timestamptz,
  fecha_reconocimiento timestamptz,
  id_usuario_reconoce uuid,
  fecha_cierre timestamptz,
  id_usuario_cierra uuid,
  estado varchar(20) not null default 'ACTIVA',
  valor_detectado numeric(24,8),
  mensaje text,
  comentario text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint eventos_alarma_estado_ck
    check (estado in ('ACTIVA', 'RECONOCIDA', 'CERRADA')),
  constraint eventos_alarma_fechas_ck
    check (
      ultima_deteccion >= fecha_inicio
      and (fecha_fin is null or fecha_fin >= fecha_inicio)
      and (fecha_reconocimiento is null or fecha_reconocimiento >= fecha_inicio)
      and (fecha_cierre is null or fecha_cierre >= fecha_inicio)
    ),
  constraint eventos_alarma_reconocimiento_ck
    check (
      (fecha_reconocimiento is null and id_usuario_reconoce is null)
      or (fecha_reconocimiento is not null and id_usuario_reconoce is not null)
    ),
  constraint eventos_alarma_reconocida_ck
    check (estado <> 'RECONOCIDA' or fecha_reconocimiento is not null),
  constraint eventos_alarma_cierre_ck
    check (
      (estado <> 'CERRADA' and fecha_cierre is null and id_usuario_cierra is null)
      or (estado = 'CERRADA' and fecha_cierre is not null and id_usuario_cierra is not null)
    )
);

-- Como máximo un evento abierto por regla y recinto.
create unique index if not exists ux_eventos_alarma_abierto
  on public.eventos_alarma(
    id_regla_alarma,
    coalesce(id_recinto, '00000000-0000-0000-0000-000000000000'::uuid)
  )
  where estado <> 'CERRADA';

create index if not exists ix_eventos_alarma_estado_fecha
  on public.eventos_alarma(estado, fecha_inicio desc);

create index if not exists ix_eventos_alarma_regla
  on public.eventos_alarma(id_regla_alarma, fecha_inicio desc);

create index if not exists ix_eventos_alarma_recinto
  on public.eventos_alarma(id_recinto, estado);

create table if not exists public.notificaciones (
  id uuid primary key default gen_random_uuid(),
  id_evento_alarma uuid references public.eventos_alarma(id) on delete restrict,
  id_sensor uuid references public.sensores(id) on delete restrict,
  tipo varchar(30) not null,
  canal varchar(20) not null default 'PLATAFORMA',
  id_usuario uuid,
  destinatario varchar(255),
  intentos smallint not null default 0,
  fecha_envio timestamptz,
  fecha_lectura timestamptz,
  estado varchar(20) not null default 'PENDIENTE',
  mensaje text not null,
  error text,
  created_at timestamptz not null default now(),
  constraint notificaciones_tipo_ck
    check (tipo in ('ALARMA', 'COMUNICACION')),
  constraint notificaciones_canal_ck
    check (canal in ('PLATAFORMA', 'EMAIL')),
  constraint notificaciones_estado_ck
    check (estado in ('PENDIENTE', 'ENVIADA', 'LEIDA', 'ERROR')),
  constraint notificaciones_envio_ck
    check (estado not in ('ENVIADA', 'LEIDA') or fecha_envio is not null),
  constraint notificaciones_intentos_ck check (intentos >= 0),
  constraint notificaciones_lectura_ck
    check (estado <> 'LEIDA' or fecha_lectura is not null)
);

create index if not exists ix_notificaciones_evento
  on public.notificaciones(id_evento_alarma);

create index if not exists ix_notificaciones_estado
  on public.notificaciones(estado, created_at);

create or replace function public.validar_regla_alarma_fuente()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_edificio uuid;
begin
  if new.id_sensor is not null then
    select p.id_edificio into v_edificio
    from public.sensores s
    join public.recintos r on r.id = s.id_recinto
    join public.plantas p on p.id = r.id_planta
    where s.id = new.id_sensor;
  else
    select me.id_edificio into v_edificio
    from public.magnitudes_edificio me
    where me.id = new.id_magnitud_edificio;
  end if;

  if v_edificio is null then
    raise exception 'El sensor o la magnitud de la regla no existe';
  end if;

  if v_edificio <> new.id_edificio then
    raise exception 'El sensor o la magnitud debe pertenecer al edificio de la regla';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_reglas_alarma_validar_fuente on public.reglas_alarma;
create trigger trg_reglas_alarma_validar_fuente
before insert or update of id_edificio, id_sensor, id_magnitud_edificio
on public.reglas_alarma
for each row execute function public.validar_regla_alarma_fuente();

-- El evento debe referirse a la fuente y a un recinto del edificio de su regla.
create or replace function public.validar_evento_alarma()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_regla public.reglas_alarma%rowtype;
begin
  select * into v_regla from public.reglas_alarma where id = new.id_regla_alarma;

  if not found then
    raise exception 'La regla del evento no existe';
  end if;

  if new.id_sensor is not null and new.id_sensor is distinct from v_regla.id_sensor then
    raise exception 'El sensor del evento no coincide con el de la regla';
  end if;

  if new.id_magnitud_edificio is not null
     and new.id_magnitud_edificio is distinct from v_regla.id_magnitud_edificio then
    raise exception 'La magnitud del evento no coincide con la de la regla';
  end if;

  if new.id_recinto is not null
     and public.obtener_edificio_recinto(new.id_recinto) is distinct from v_regla.id_edificio then
    raise exception 'El recinto del evento no pertenece al edificio de la regla';
  end if;

  return new;
end;
$$;

drop trigger if exists trg_eventos_alarma_validar on public.eventos_alarma;
create trigger trg_eventos_alarma_validar
before insert or update of id_regla_alarma, id_sensor, id_magnitud_edificio, id_recinto
on public.eventos_alarma
for each row execute function public.validar_evento_alarma();

