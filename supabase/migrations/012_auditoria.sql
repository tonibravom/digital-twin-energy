begin;

-- =========================================================
-- AUDITORÍA AUTOMÁTICA DE CONFIGURACIÓN (maestro §13)
-- Triggers sobre tablas de configuración. No se audita cada
-- lectura ni valor calculado. Nadie puede escribir en la tabla
-- directamente: solo el trigger (security definer).
-- En modificaciones se guardan únicamente los campos cambiados.
-- =========================================================

create table if not exists public.auditoria (
  id bigint generated by default as identity primary key,
  id_usuario uuid references public.usuarios(id) on delete set null,
  auth_user_id uuid,
  rol_bd text,
  id_edificio uuid references public.edificios(id) on delete set null,
  tabla varchar(120) not null,
  id_registro text not null,
  accion varchar(20) not null,
  datos_anteriores jsonb,
  datos_nuevos jsonb,
  fecha timestamptz not null default now(),
  descripcion text,
  constraint auditoria_accion_ck
    check (accion in ('ALTA', 'MODIFICACION', 'BAJA', 'ELIMINACION'))
);

create index if not exists ix_auditoria_fecha
  on public.auditoria(fecha desc);
create index if not exists ix_auditoria_usuario_fecha
  on public.auditoria(id_usuario, fecha desc);
create index if not exists ix_auditoria_edificio_fecha
  on public.auditoria(id_edificio, fecha desc);
create index if not exists ix_auditoria_tabla_registro
  on public.auditoria(tabla, id_registro);

alter table public.auditoria enable row level security;
revoke insert, update, delete, truncate on public.auditoria from anon, authenticated;

comment on table public.auditoria is
  'Registro automático de altas, modificaciones y bajas de configuración. Solo lo escriben los triggers de auditoría.';

-- Resuelve el edificio afectado a partir de la fila auditada.
create or replace function public.edificio_de_fila_auditada(
  p_tabla text,
  p_fila jsonb
)
returns uuid
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v uuid;
begin
  if p_tabla = 'edificios' then
    return (p_fila->>'id')::uuid;
  end if;

  if p_fila ? 'id_edificio' and p_fila->>'id_edificio' is not null then
    return (p_fila->>'id_edificio')::uuid;
  end if;

  if p_fila ? 'id_recinto' and p_fila->>'id_recinto' is not null then
    return public.obtener_edificio_recinto((p_fila->>'id_recinto')::uuid);
  end if;

  if p_tabla = 'recintos' or (p_fila ? 'id_planta' and p_fila->>'id_planta' is not null) then
    select p.id_edificio into v from public.plantas p
    where p.id = (p_fila->>'id_planta')::uuid;
    return v;
  end if;

  if p_fila ? 'id_sensor' and p_fila->>'id_sensor' is not null then
    select public.obtener_edificio_recinto(s.id_recinto) into v
    from public.sensores s where s.id = (p_fila->>'id_sensor')::uuid;
    return v;
  end if;

  if p_fila ? 'id_dispositivo' and p_fila->>'id_dispositivo' is not null then
    select public.obtener_edificio_recinto(d.id_recinto) into v
    from public.dispositivos d where d.id = (p_fila->>'id_dispositivo')::uuid;
    return v;
  end if;

  if p_fila ? 'id_suministro' then
    select s.id_edificio into v from public.suministros s
    where s.id = (p_fila->>'id_suministro')::uuid;
    return v;
  end if;

  if p_fila ? 'id_magnitud_edificio' then
    select me.id_edificio into v from public.magnitudes_edificio me
    where me.id = (p_fila->>'id_magnitud_edificio')::uuid;
    return v;
  end if;

  if p_fila ? 'id_regla_alarma' then
    select ra.id_edificio into v from public.reglas_alarma ra
    where ra.id = (p_fila->>'id_regla_alarma')::uuid;
    return v;
  end if;

  if p_fila ? 'id_modelo_3d' then
    select m.id_edificio into v from public.modelos_3d m
    where m.id = (p_fila->>'id_modelo_3d')::uuid;
    return v;
  end if;

  return null;
end;
$$;

create or replace function public.auditar_cambio()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_ant jsonb;
  v_nue jsonb;
  v_fila jsonb;
  v_accion text;
  v_auth uuid;
  v_usuario uuid;
  v_id text;
  k text;
begin
  if tg_op = 'INSERT' then
    v_nue := pg_catalog.to_jsonb(new);
    v_fila := v_nue;
    v_accion := 'ALTA';
  elsif tg_op = 'DELETE' then
    v_ant := pg_catalog.to_jsonb(old);
    v_fila := v_ant;
    v_accion := 'ELIMINACION';
  else
    v_ant := pg_catalog.to_jsonb(old);
    v_nue := pg_catalog.to_jsonb(new);
    v_fila := v_nue;

    -- Guardar solo los campos modificados (sin updated_at).
    for k in select pg_catalog.jsonb_object_keys(v_nue) loop
      if k = 'updated_at' or (v_ant->k) is not distinct from (v_nue->k) then
        v_ant := v_ant - k;
        v_nue := v_nue - k;
      end if;
    end loop;

    if v_nue = '{}'::jsonb then
      return null;
    end if;

    if (v_nue->>'activo' = 'false') or (v_nue->>'activa' = 'false')
       or (v_nue->>'estado' = 'BAJA') then
      v_accion := 'BAJA';
    else
      v_accion := 'MODIFICACION';
    end if;
  end if;

  v_id := coalesce(
    v_fila->>'id',
    v_fila->>'id_suministro',
    concat_ws('|',
      v_fila->>'id_regla_alarma', v_fila->>'id_recinto', v_fila->>'id_usuario',
      v_fila->>'id_rol', v_fila->>'id_permiso')
  );

  begin
    v_auth := auth.uid();
  exception when others then
    v_auth := null;
  end;

  if v_auth is not null then
    select u.id into v_usuario from public.usuarios u where u.auth_user_id = v_auth;
  end if;

  insert into public.auditoria (
    id_usuario, auth_user_id, rol_bd, id_edificio, tabla, id_registro,
    accion, datos_anteriores, datos_nuevos
  )
  values (
    v_usuario, v_auth, pg_catalog.current_setting('role', true),
    public.edificio_de_fila_auditada(tg_table_name::text, v_fila),
    tg_table_name, coalesce(nullif(v_id, ''), '?'),
    v_accion, v_ant, v_nue
  );

  return null;
end;
$$;

revoke all on function public.edificio_de_fila_auditada(text, jsonb) from public, anon, authenticated;
revoke all on function public.auditar_cambio() from public, anon, authenticated;

-- Tablas de configuración auditadas.
do $$
declare
  t text;
begin
  foreach t in array array[
    'proveedores', 'clientes', 'proveedores_clientes', 'edificios',
    'proveedores_edificios', 'plantas', 'recintos', 'conexiones',
    'dispositivos', 'sensores', 'dispositivos_recintos_ambito',
    'sensores_recintos_ambito', 'magnitudes_edificio', 'magnitudes_fuentes',
    'suministros', 'suministros_electricidad', 'suministros_gas',
    'suministros_agua', 'suministros_agua_incendios', 'suministros_generacion',
    'suministros_dispositivos', 'modelos_3d', 'ubicaciones_3d',
    'reglas_alarma', 'reglas_alarma_recintos', 'reglas_alarma_usuarios',
    'calendario_edificio', 'modalidades_edificio', 'complementos_edificio',
    'parametros_saas', 'usuarios', 'usuarios_partners', 'usuarios_clientes',
    'usuarios_edificios', 'roles_permisos'
  ] loop
    execute pg_catalog.format('drop trigger if exists trg_auditoria on public.%I', t);
    execute pg_catalog.format(
      'create trigger trg_auditoria after insert or update or delete on public.%I
         for each row execute function public.auditar_cambio()', t);
  end loop;
end;
$$;

commit;
