create table if not exists public.roles (
  id smallint generated by default as identity primary key,
  codigo varchar(50) not null unique,
  nombre varchar(120) not null,
  descripcion text,
  activo boolean not null default true
);

create table if not exists public.permisos (
  id integer generated by default as identity primary key,
  codigo varchar(100) not null unique,
  nombre varchar(150) not null,
  modulo varchar(60) not null,
  descripcion text,
  activo boolean not null default true
);

create table if not exists public.roles_permisos (
  id_rol smallint not null references public.roles(id) on delete restrict,
  id_permiso integer not null references public.permisos(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (id_rol, id_permiso)
);

create table if not exists public.usuarios (
  id uuid primary key default gen_random_uuid(),
  auth_user_id uuid not null unique references auth.users(id) on delete restrict,
  nombre varchar(120) not null,
  apellidos varchar(180),
  email varchar(255) not null,
  telefono varchar(50),
  id_rol smallint not null references public.roles(id) on delete restrict,
  activo boolean not null default true,
  fecha_alta date not null default current_date,
  fecha_baja date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint usuarios_email_formato_ck
    check (position('@' in email) > 1),
  constraint usuarios_fechas_ck
    check (fecha_baja is null or fecha_baja >= fecha_alta),
  constraint usuarios_estado_fecha_ck
    check ((activo and fecha_baja is null) or (not activo and fecha_baja is not null))
);

create unique index if not exists ux_usuarios_email_lower
  on public.usuarios (lower(email));

create index if not exists ix_usuarios_rol_activo
  on public.usuarios(id_rol, activo);

create table if not exists public.usuarios_partners (
  id uuid primary key default gen_random_uuid(),
  id_usuario uuid not null references public.usuarios(id) on delete restrict,
  id_proveedor uuid not null references public.proveedores(id) on delete restrict,
  tipo_alcance varchar(20) not null default 'MASTER',
  fecha_inicio date not null default current_date,
  fecha_fin date,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  constraint usuarios_partners_alcance_ck
    check (tipo_alcance in ('MASTER', 'RESTRINGIDO')),
  constraint usuarios_partners_fechas_ck
    check (fecha_fin is null or fecha_fin >= fecha_inicio),
  constraint usuarios_partners_estado_fecha_ck
    check ((activo and fecha_fin is null) or (not activo and fecha_fin is not null))
);

create unique index if not exists ux_usuarios_partners_activo
  on public.usuarios_partners(id_usuario, id_proveedor)
  where activo;

create index if not exists ix_usuarios_partners_proveedor
  on public.usuarios_partners(id_proveedor, activo);

create table if not exists public.usuarios_clientes (
  id uuid primary key default gen_random_uuid(),
  id_usuario uuid not null references public.usuarios(id) on delete restrict,
  id_cliente uuid not null references public.clientes(id) on delete restrict,
  tipo_alcance varchar(20) not null default 'MASTER',
  fecha_inicio date not null default current_date,
  fecha_fin date,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  constraint usuarios_clientes_alcance_ck
    check (tipo_alcance in ('MASTER', 'RESTRINGIDO')),
  constraint usuarios_clientes_fechas_ck
    check (fecha_fin is null or fecha_fin >= fecha_inicio),
  constraint usuarios_clientes_estado_fecha_ck
    check ((activo and fecha_fin is null) or (not activo and fecha_fin is not null))
);

create unique index if not exists ux_usuarios_clientes_activo
  on public.usuarios_clientes(id_usuario, id_cliente)
  where activo;

create index if not exists ix_usuarios_clientes_cliente
  on public.usuarios_clientes(id_cliente, activo);

create table if not exists public.usuarios_edificios (
  id uuid primary key default gen_random_uuid(),
  id_usuario uuid not null references public.usuarios(id) on delete restrict,
  id_edificio uuid not null references public.edificios(id) on delete restrict,
  fecha_inicio date not null default current_date,
  fecha_fin date,
  activo boolean not null default true,
  created_at timestamptz not null default now(),
  constraint usuarios_edificios_fechas_ck
    check (fecha_fin is null or fecha_fin >= fecha_inicio),
  constraint usuarios_edificios_estado_fecha_ck
    check ((activo and fecha_fin is null) or (not activo and fecha_fin is not null))
);

create unique index if not exists ux_usuarios_edificios_activo
